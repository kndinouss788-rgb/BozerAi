"""Safe dictionary-first and optional neural translation pipeline."""
from dataclasses import dataclass
from typing import Any

from .moore_french import MooreFrenchTranslator, TranslationResult


@dataclass(frozen=True)
class TranslationRequest:
    text: str
    source_language: str
    target_language: str


@dataclass(frozen=True)
class TranslationResponse:
    result: TranslationResult
    sentence_level_supported: bool = False
    requires_human_review: bool = False


class TranslationPipeline:
    """Use reviewed exact entries first; use a cleared neural backend for new text.

    Candidate dictionary entries remain visibly provisional. Neural output is
    always marked model-generated and requires native-speaker review.
    """

    def __init__(self, translator: MooreFrenchTranslator, sentence_backend: Any = None):
        self.translator = translator
        self.sentence_backend = sentence_backend

    def translate(self, request: TranslationRequest) -> TranslationResponse:
        result = self.translator.translate(
            request.text, request.source_language, request.target_language
        )
        if result.status != "not_found" or self.sentence_backend is None:
            return TranslationResponse(
                result=result,
                sentence_level_supported=False,
                requires_human_review=result.status in {"not_found", "ambiguous", "candidate"},
            )

        translated = self.sentence_backend.translate(
            request.text, request.source_language, request.target_language
        )
        model_id = getattr(self.sentence_backend, "model_id", "configured local model")
        license_id = getattr(self.sentence_backend, "license_id", None)
        model_result = TranslationResult(
            source_text=request.text,
            translated_text=translated,
            source_language=request.source_language,
            target_language=request.target_language,
            status="model",
            confidence="model_generated",
            note=(
                f"Generated by {model_id}; native Mooré review is required before "
                "treating this translation as validated."
            ),
            source=f"Local neural checkpoint: {model_id}",
            source_license=license_id,
            native_review_status="pending",
        )
        return TranslationResponse(
            result=model_result,
            sentence_level_supported=True,
            requires_human_review=True,
        )
